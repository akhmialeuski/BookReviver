# Identifier and message of the revision a test adds after the head of the shipped migrations
TEST_REVISION: str = 'test_revision'
TEST_REVISION_MESSAGE: str = 'A revision a test adds after the baseline.'
# The line of script.py.mako that opens the body of schema_upgrades, after which a test writes its operations
SCHEMA_UPGRADES_DOCSTRING: str = '    """Change the schema to this revision."""'
# The column REBUILD_PROJECTS adds
REBUILT_COLUMN: str = 'probe'
# Adds a column to projects, which batch mode on SQLite does by copying, dropping and renaming the table
REBUILD_PROJECTS: str = f"""    with op.batch_alter_table('projects', recreate='always') as batch_op:
        batch_op.add_column(sa.Column('{REBUILT_COLUMN}', sa.String(), nullable=False, server_default=''))"""
# Rebuilds projects, then deletes every project, which leaves the rows of its book pointing at no project while
# foreign keys are off, so the migration changes both the schema and the rows before its check fails
ORPHAN_THE_BOOK: str = f"{REBUILD_PROJECTS}\n    op.execute('DELETE FROM projects')"
# Changes the type of a column of projects, which only a comparison of types notices
RETYPE_A_COLUMN: str = """    with op.batch_alter_table('projects') as batch_op:
        batch_op.alter_column({column!r}, type_=sa.{new_type}())"""
# Changes nothing, standing for a revision of a branch that the checked-out code does not ship
NO_CHANGE: str = ''
# The tables holding the rows of a book, each of which refers to the project or to a row that does
BOOK_TABLES: tuple[type[CommonTableAttributes], ...] = (ProjectRow, SourceRow, ScanRow, PageRow, PageVersionRow, JobRow)


@pytest.fixture
async def fx_container(fx_settings: Settings) -> AsyncIterator[AsyncContainer]:
    """Yield the application's container on the SQL backend, with no schema created for it.

    :param fx_settings: Settings pointing at a fresh data directory of the test.
    :type fx_settings: Settings
    :returns: Iterator yielding the container and closing it afterwards.
    :rtype: AsyncIterator[AsyncContainer]
    """
    container = build_container(fx_settings.model_copy(update={'persistence': PersistenceBackend.SQLALCHEMY}))
    yield container
    await container.close()


@pytest.fixture
async def fx_empty_database(fx_settings: Settings) -> AsyncIterator[SqlDatabase]:
    """Open a database with no table, at the URL the settings name.

    :param fx_settings: Settings pointing at a fresh data directory of the test.
    :type fx_settings: Settings
    :returns: Iterator yielding the database and disposing of its engine afterwards.
    :rtype: AsyncIterator[SqlDatabase]
    """
    fx_settings.data_dir.mkdir(parents=True)
    database = SqlDatabase(fx_settings.resolved_database_url)
    yield database
    await database.dispose()


async def _migrate(database: SqlDatabase, command: Callable[..., None], *args: str) -> None:
    """Run an Alembic command in a worker thread, after closing the connections the test's event loop opened.

    :param database: Database the command runs on, whose pool is emptied first.
    :type database: SqlDatabase
    :param command: Command of ``AlembicCommands``, such as ``upgrade``.
    :type command: Callable[..., None]
    :param args: Arguments of the command, such as the target revision.
    :type args: str
    """
    await database.dispose()
    await asyncify(command)(*args)


async def _commit_book(database: SqlDatabase) -> ProjectId:
    """Commit a project whose cover is a page cut from a scan, with its source, the page's version and a job.

    :param database: Migrated database to commit into.
    :type database: SqlDatabase
    :returns: Identifier of the project.
    :rtype: ProjectId
    """
    project = make_project(owner_id=await commit_account(database))
    source = make_source(project_id=project.id)
    scan = make_scan(source=source, number=0)
    page = make_page(project_id=project.id, scan=scan)
    async with database.sessions() as session:
        uow = SqlAlchemyUnitOfWork(session)
        await uow.projects.add(project)
        await uow.sources.add(source)
        await uow.scans.add(scan)
        await uow.pages.add(page)
        await uow.page_versions.add(make_page_version(page_id=page.id))
        await uow.jobs.add(make_job(project_id=project.id))
        await uow.projects.update(evolve(project, cover_page_id=page.id))
        await uow.commit()
    return project.id


def _migrations_with_revision(database: SqlDatabase, target: Path, upgrade: str) -> AlembicCommands:
    """Copy the shipped migrations to ``target``, add a revision after their head, and point ``database`` at them.

    The revision is rendered from the shipped ``script.py.mako``, as ``make-migrations`` renders one, so the tests
    run a revision exactly as the template writes it, and ``upgrade`` fills its ``schema_upgrades``.

    :param database: Database whose configuration is pointed at the copied migrations.
    :type database: SqlDatabase
    :param target: Directory the migrations are copied to.
    :type target: Path
    :param upgrade: Indented body of the new revision's ``upgrade``.
    :type upgrade: str
    :returns: Alembic commands over the database and the copied migrations.
    :rtype: AlembicCommands
    """
    scripts = shutil.copytree(MIGRATIONS_DIR, target, ignore=shutil.ignore_patterns('__pycache__'))
    database.config.alembic_config.script_location = str(scripts)
    migrations = AlembicCommands(database.config)
    migrations.revision(message=TEST_REVISION_MESSAGE, rev_id=TEST_REVISION)
    revision = Path(ScriptDirectory(str(scripts)).get_revision(TEST_REVISION).path)
    source = revision.read_text(encoding='utf-8')
    filled = source.replace(SCHEMA_UPGRADES_DOCSTRING, f'{SCHEMA_UPGRADES_DOCSTRING}\n{upgrade}', 1)
    revision.write_text(filled, encoding='utf-8')
    return migrations


class TestBaseline:
    """Tests for the baseline revision, the one head of the shipped migrations."""

    def test_history_has_exactly_one_head(self) -> None:
        """Verify the migrations have one head, so ``upgrade head`` names one schema."""
        assert len(ScriptDirectory(str(MIGRATIONS_DIR)).get_heads()) == 1

    async def test_upgrade_and_downgrade_match_the_models(self, fx_empty_database: SqlDatabase) -> None:
        """Verify upgrading an empty database leaves nothing for autogenerate, and a downgrade and upgrade again too.

        ``alembic check`` raises when the database differs from the tables in any table, column, type, key or index.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        """
        migrations = fx_empty_database.migrations
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        await _migrate(fx_empty_database, migrations.check)
        await _migrate(fx_empty_database, migrations.downgrade, 'base')
        async with fx_empty_database.engine.connect() as connection:
            left = await connection.run_sync(lambda sync_connection: inspect(sync_connection).get_table_names())
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        await _migrate(fx_empty_database, migrations.check)
        assert left == [fx_empty_database.config.alembic_config.version_table_name]


class TestDatabaseProvider:
    """Tests for DatabaseProvider.database, which opens the database only at the head revision."""

    async def test_refuses_a_database_no_revision_was_applied_to(self, fx_container: AsyncContainer) -> None:
        """Verify the application does not start on an unmigrated database and names the command that migrates it.

        :param fx_container: The application's container on the SQL backend, with no schema.
        :type fx_container: AsyncContainer
        """
        head = ScriptDirectory(str(MIGRATIONS_DIR)).get_current_head()
        expected = f'Database schema is at revision none, code expects {head}: run `{MIGRATE_COMMAND}`'
        with pytest.raises(RuntimeError, match=re.escape(expected)):
            await fx_container.get(SqlDatabase)

    async def test_refuses_a_database_migrated_by_code_it_does_not_ship(
        self, fx_container: AsyncContainer, fx_empty_database: SqlDatabase, tmp_path: Path
    ) -> None:
        """Verify a database migrated on another branch is refused with the downgrade that returns it, not an upgrade.

        ``upgrade head`` cannot help here: Alembic cannot locate the revision the database records.

        :param fx_container: The application's container on the SQL backend.
        :type fx_container: AsyncContainer
        :param fx_empty_database: The same database, which the test migrates with a revision the code does not ship.
        :type fx_empty_database: SqlDatabase
        :param tmp_path: Temporary directory of the test, holding the migrations of the other branch.
        :type tmp_path: Path
        """
        head = ScriptDirectory(str(MIGRATIONS_DIR)).get_current_head()
        branch = _migrations_with_revision(fx_empty_database, tmp_path / 'migrations', NO_CHANGE)
        await _migrate(fx_empty_database, branch.upgrade, 'head')
        expected = (
            f'Database schema is at revision {TEST_REVISION}, which this code does not ship, and code expects {head}: '
            f'run `{MIGRATE_DOWNGRADE_COMMAND} {head}` with the code that ships {TEST_REVISION}, '
            f'or restore the copy of the data directory made before migrating'
        )
        with pytest.raises(RuntimeError, match=re.escape(expected)):
            await fx_container.get(SqlDatabase)

    async def test_opens_a_database_at_the_head_revision(
        self, fx_container: AsyncContainer, fx_empty_database: SqlDatabase
    ) -> None:
        """Verify the application starts once the migrations are applied, and leaves the schema as they left it.

        :param fx_container: The application's container on the SQL backend.
        :type fx_container: AsyncContainer
        :param fx_empty_database: The same database, which the test migrates first.
        :type fx_empty_database: SqlDatabase
        """
        await _migrate(fx_empty_database, fx_empty_database.migrations.upgrade, 'head')
        database = await fx_container.get(SqlDatabase)
        assert (await database.schema_revisions()).is_current


