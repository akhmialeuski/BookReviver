"""Tests for the migrations of the two schemas, and for the application's refusal to start on a catalogue not at head.

The baseline of each schema builds the tables of its models, a migration of a book keeps the rows of the book, and the
application starts only on a catalogue at the head revision. Alembic runs its commands on the synchronous engine of
the writer, so the tests run them in a worker thread through ``_migrate``, and set rows up and read them back in
sessions of that engine, which they close before a command runs, since the pool of the writer holds one connection.
"""

