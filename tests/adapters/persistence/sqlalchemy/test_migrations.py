async def _migrate(database: SqlDatabase, command: Callable[..., None], *args: str) -> None:
    """Run an Alembic command in a worker thread, after closing the connections the test's event loop opened.

    :param database: Database the command runs on, whose pool is emptied first.
    :type database: SqlDatabase
    :param command: Command of ``AlembicCommands``, such as ``upgrade``.
    :type command: Callable[..., None]
    :param args: Arguments of the command, such as the target revision.
    :type args: str
    """
    await database.dispose()
    await to_thread.run_sync(command, *args)


async def _commit_book(database: SqlDatabase) -> ProjectId:
    """Commit a project whose cover is a page cut from a scan, with its source, the page's version and a job.

    :param database: Migrated database to commit into.
    :type database: SqlDatabase
    :returns: Identifier of the project.
    :rtype: ProjectId
    """
    project = make_project(owner_id=await commit_account(database))
    source = make_source(project_id=project.id)
    scan = make_scan(source=source, number=0)
    page = make_page(project_id=project.id, scan=scan)
    async with database.sessions() as session:
        uow = SqlAlchemyUnitOfWork(session)
        await store_project(
            uow,
            project,
            page,
            sources=[source],
            scans=[scan],
            versions=[make_page_version(page_id=page.id)],
        )
        async with uow.change():
            await uow.jobs.add(make_job(project_id=project.id))
            await uow.projects.update(evolve(project, cover_page_id=page.id))
    return project.id


def _migrations_with_revision(database: SqlDatabase, target: Path, upgrade: str) -> AlembicCommands:
    """Copy the shipped migrations to ``target``, add a revision after their head, and point ``database`` at them.

    The revision is rendered from the shipped ``script.py.mako``, as ``make-migrations`` renders one, so the tests
    run a revision exactly as the template writes it, and ``upgrade`` fills its ``schema_upgrades``.

    :param database: Database whose configuration is pointed at the copied migrations.
    :type database: SqlDatabase
    :param target: Directory the migrations are copied to.
    :type target: Path
    :param upgrade: Indented body of the new revision's ``upgrade``.
    :type upgrade: str
    :returns: Alembic commands over the database and the copied migrations.
    :rtype: AlembicCommands
    """
    scripts = shutil.copytree(MIGRATIONS_DIR, target, ignore=shutil.ignore_patterns('__pycache__'))
    database.config.alembic_config.script_location = str(scripts)
    migrations = AlembicCommands(database.config)
    migrations.revision(message=TEST_REVISION_MESSAGE, rev_id=TEST_REVISION)
    revision = Path(ScriptDirectory(str(scripts)).get_revision(TEST_REVISION).path)
    source = revision.read_text(encoding='utf-8')
    filled = source.replace(SCHEMA_UPGRADES_DOCSTRING, f'{SCHEMA_UPGRADES_DOCSTRING}\n{upgrade}', 1)
    revision.write_text(filled, encoding='utf-8')
    return migrations


class TestBaseline:
    """Tests for the baseline revision, the one head of the shipped migrations."""

    def test_history_has_exactly_one_head(self) -> None:
        """Verify the migrations have one head, so ``upgrade head`` names one schema."""
        assert len(ScriptDirectory(str(MIGRATIONS_DIR)).get_heads()) == 1

    async def test_upgrade_and_downgrade_match_the_models(self, fx_empty_database: SqlDatabase) -> None:
        """Verify upgrading an empty database leaves nothing for autogenerate, and a downgrade and upgrade again too.

        ``alembic check`` raises when the database differs from the tables in any table, column, type, key or index.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        """
        migrations = fx_empty_database.migrations
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        await _migrate(fx_empty_database, migrations.check)
        await _migrate(fx_empty_database, migrations.downgrade, 'base')
        async with fx_empty_database.engine.connect() as connection:
            left = await connection.run_sync(lambda sync_connection: inspect(sync_connection).get_table_names())
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        await _migrate(fx_empty_database, migrations.check)
        assert left == [fx_empty_database.config.alembic_config.version_table_name]


class TestRecordFullFormatRevision:
    """Tests for the revision that records the format of the ``full`` image of scans and page versions."""

    async def test_images_stored_before_the_format_was_recorded_read_as_jpeg(
        self, fx_empty_database: SqlDatabase
    ) -> None:
        """Verify a downgrade past the revision and an upgrade again leave every stored image a JPEG.

        The downgrade drops the column, so the rows come back as the rows of a database migrated from before the
        revision: a scan takes the server default, a version with an image is set by the revision, and a version of a
        step without an image keeps a null.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        """
        migrations = fx_empty_database.migrations
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        project = make_project(owner_id=await commit_account(fx_empty_database))
        source = make_source(project_id=project.id)
        png = Renditions(ready=True, full=Rendition.FULL_PNG)
        scan = evolve(make_scan(source=source, number=0), renditions=png)
        page = make_page(project_id=project.id, scan=scan)
        with_image = evolve(make_page_version(page_id=page.id), renditions=png)
        without_image = evolve(make_page_version(page_id=page.id, minutes=1), renditions=None)
        async with fx_empty_database.sessions() as session:
            await store_project(
                SqlAlchemyUnitOfWork(session),
                project,
                page,
                sources=[source],
                scans=[scan],
                versions=[with_image, without_image],
            )

        await _migrate(fx_empty_database, migrations.downgrade, PREVIOUS_REVISION)
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        async with fx_empty_database.sessions() as session:
            scans = (await session.execute(select(ScanRow.renditions_full))).scalars().all()
            rows = (await session.execute(select(PageVersionRow.id, PageVersionRow.renditions_full))).all()
        versions = {row.id: row.renditions_full for row in rows}

        expect(scans == [Rendition.FULL_JPEG])
        expect(versions == {with_image.id: Rendition.FULL_JPEG, without_image.id: None})
        assert_expectations()


class TestPaginationSectionsRevision:
    """Tests for the revision that adds the pagination sections and the mark of a label written by hand."""

    async def test_every_label_that_exists_becomes_an_exception_of_the_sections(
        self, fx_empty_database: SqlDatabase
    ) -> None:
        """Verify a downgrade past the revision and an upgrade again keep each label and mark the labels as exceptions.

        The downgrade drops the mark, so the pages come back as the pages of a database migrated from before the
        revision: the labels a person typed, or that came with a scan, are all there is, and none may be lost.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        """
        migrations = fx_empty_database.migrations
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        project = make_project(owner_id=await commit_account(fx_empty_database))
        typed = evolve(make_page(project_id=project.id, order_key='a0'), label=TYPED_LABEL)
        bracketed = evolve(make_page(project_id=project.id, order_key='a1'), label=BRACKETED_LABEL)
        bare = make_page(project_id=project.id, order_key='a2')
        async with fx_empty_database.sessions() as session:
            await store_project(SqlAlchemyUnitOfWork(session), project, typed, bracketed, bare)

        await _migrate(fx_empty_database, migrations.downgrade, BEFORE_SECTIONS_REVISION)
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        async with fx_empty_database.sessions() as session:
            rows = (await session.execute(select(PageRow.id, PageRow.label, PageRow.label_manual))).all()

        stored = {row.id: (row.label, row.label_manual) for row in rows}
        expect(
            stored
            == {
                typed.id: (TYPED_LABEL, True),
                bracketed.id: (BRACKETED_LABEL, True),
                bare.id: ('', False),
            }
        )
        assert_expectations()


