@contextmanager
def _session(database: SqlDatabase) -> Iterator[Session]:
    """Open a session of the writer's engine, for a test that reads rows back.

    Leaving the block closes the session, which gives the one connection of the writer back, so a migration command
    may take it next.

    :param database: Database whose engine of the writer the session is bound to.
    :type database: SqlDatabase
    :returns: Iterator yielding the session.
    :rtype: Iterator[Session]
    """
    with Session(database.engine) as session:
        yield session


def _checks(database: SqlDatabase) -> dict[str, set[str]]:
    """Read the names of the checks of every table of a database, the version table left out.

    :param database: The database.
    :type database: SqlDatabase
    :returns: The names of the checks of each table.
    :rtype: dict[str, set[str]]
    """
    with database.engine.connect() as connection:
        inspector = inspect(connection)
        tables = set(inspector.get_table_names()) - {database.config.alembic_config.version_table_name}
        return {table: {str(check['name']) for check in inspector.get_check_constraints(table)} for table in tables}


def _primary_keys(database: SqlDatabase) -> dict[str, list[str]]:
    """Read the columns of the primary key of every table of a database, the version table left out.

    :param database: The database.
    :type database: SqlDatabase
    :returns: The columns of the primary key of each table, in key order.
    :rtype: dict[str, list[str]]
    """
    with database.engine.connect() as connection:
        inspector = inspect(connection)
        tables = set(inspector.get_table_names()) - {database.config.alembic_config.version_table_name}
        return {table: list(inspector.get_pk_constraint(table)['constrained_columns']) for table in tables}


async def _migrate(database: SqlDatabase, command: Callable[..., None], *args: str) -> None:
    """Run an Alembic command in a worker thread, after closing the connections the test opened.

    :param database: Database the command runs on, whose pool is emptied first.
    :type database: SqlDatabase
    :param command: Command of ``AlembicCommands``, such as ``upgrade``.
    :type command: Callable[..., None]
    :param args: Arguments of the command, such as the target revision.
    :type args: str
    """
    await database.dispose()
    await to_thread.run_sync(command, *args)


async def _commit_book(database: SqlDatabase) -> None:
    """Commit a book with a page cut from a scan, its source and the page's version.

    :param database: Migrated database of a book to commit into.
    :type database: SqlDatabase
    """
    book_record = make_record()
    source = make_source()
    scan = make_scan(source=source, number=0)
    page = make_page(scan=scan)

    def store(session: Session) -> None:
        """Store the book in the order its keys need.

        :param session: Session of the transaction.
        :type session: Session
        """
        repos = SqlAlchemyBookRepositories(session)
        repos.book_record.add(book_record)
        repos.sources.add(source)
        repos.scans.add(scan)
        repos.pages.add(page)
        repos.page_versions.add(make_page_version(page_id=page.id))

    await database.write(store, kind=BlockKind.BOOK, book=None, wait_seconds=DEFAULT_CHANGE_WAIT_SECONDS)


def _migrations_with_revision(database: SqlDatabase, target: Path, upgrade: str) -> AlembicCommands:
    """Copy the shipped migrations of the schema of ``database`` to ``target``, add a revision after their head.

    The revision is rendered from the shipped ``script.py.mako``, as ``make-migrations`` renders one, so the tests
    run a revision exactly as the template writes it, and ``upgrade`` fills its ``schema_upgrades``.

    :param database: Database whose configuration is pointed at the copied migrations.
    :type database: SqlDatabase
    :param target: Directory the migrations are copied to.
    :type target: Path
    :param upgrade: Indented body of the new revision's ``upgrade``.
    :type upgrade: str
    :returns: Alembic commands over the database and the copied migrations.
    :rtype: AlembicCommands
    """
    scripts = shutil.copytree(database.schema.migrations, target, ignore=shutil.ignore_patterns('__pycache__'))
    database.config.alembic_config.script_location = str(scripts)
    migrations = AlembicCommands(database.config)
    migrations.revision(message=TEST_REVISION_MESSAGE, rev_id=TEST_REVISION)
    revision = Path(ScriptDirectory(str(scripts)).get_revision(TEST_REVISION).path)
    source = revision.read_text(encoding=ENCODING)
    filled = source.replace(SCHEMA_UPGRADES_DOCSTRING, f'{SCHEMA_UPGRADES_DOCSTRING}\n{upgrade}', 1)
    revision.write_text(filled, encoding=ENCODING)
    return migrations


class TestBaseline:
    """Tests for the baseline revision of each schema, the one head of its shipped migrations."""

    @pytest.mark.parametrize('schema', list(Schema))
    def test_history_has_exactly_one_head(self, schema: Schema) -> None:
        """Verify the migrations of a schema have one head, so ``upgrade head`` names one schema.

        :param schema: The schema whose migrations are read.
        :type schema: Schema
        """
        assert len(ScriptDirectory(str(schema.migrations)).get_heads()) == 1

    async def test_upgrade_and_downgrade_match_the_models(self, fx_empty_database: SqlDatabase) -> None:
        """Verify upgrading an empty file leaves nothing for autogenerate, and a downgrade and upgrade again too.

        ``alembic check`` raises when the database differs from the tables in any table, column, type, key or index.

        :param fx_empty_database: Database of a schema with no table.
        :type fx_empty_database: SqlDatabase
        """
        database = fx_empty_database
        migrations = database.migrations
        await _migrate(database, migrations.upgrade, HEAD)
        await _migrate(database, migrations.check)
        await _migrate(database, migrations.downgrade, BASE)
        with database.engine.connect() as connection:
            left = inspect(connection).get_table_names()
        await _migrate(database, migrations.upgrade, HEAD)
        await _migrate(database, migrations.check)
        assert left == [database.config.alembic_config.version_table_name]

    async def test_the_revisions_add_every_check_and_primary_key_of_the_tables(
        self, fx_empty_database: SqlDatabase, tmp_path: Path
    ) -> None:
        """Verify the revisions leave every ``CHECK`` and primary key the tables declare, which ``alembic check`` skips.

        A file built by the revisions and one built from the tables are read back by SQLAlchemy's inspector, which reads
        the checks of SQLite from the SQL of each table.

        :param fx_empty_database: Database of a schema with no table.
        :type fx_empty_database: SqlDatabase
        :param tmp_path: Temporary directory of the test, holding the file built from the tables.
        :type tmp_path: Path
        """
        await _migrate(fx_empty_database, fx_empty_database.migrations.upgrade, HEAD)
        reference = SqlDatabase(
            f'sqlite:///{tmp_path / REFERENCE_FILE}', schema=fx_empty_database.schema, tracer=NullTracer()
        )
        try:
            with reference.engine.begin() as connection:
                fx_empty_database.schema.metadata.create_all(connection)
            expect(_checks(fx_empty_database) == _checks(reference))
            expect(_primary_keys(fx_empty_database) == _primary_keys(reference))
            assert_expectations()
        finally:
            await reference.dispose()

    def test_no_table_of_a_book_names_an_account(self) -> None:
        """Verify no column of the schema of a book holds or refers to an account, so a book moves as it is."""
        names = {(table.name, column.name) for table in Schema.BOOK.metadata.tables.values() for column in table.c}
        keys = {key.column.table.name for table in Schema.BOOK.metadata.tables.values() for key in table.foreign_keys}
        expect(not {name for name in names if name[1] in {'owner_id', 'account_id'}}, names)
        expect(keys <= set(Schema.BOOK.metadata.tables), keys)
        assert_expectations()


