class TestEnv:
    """Tests for env.py, which runs a migration on SQLite with foreign keys off and checks them afterwards."""

    async def test_batch_rebuild_of_projects_keeps_the_rows_of_its_book(
        self, fx_empty_database: SqlDatabase, tmp_path: Path
    ) -> None:
        """Verify a revision rebuilding projects in batch mode leaves every row of the book and the project's cover.

        With foreign keys on, dropping the old projects table would cascade to the sources, scans, pages, versions
        and jobs.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        :param tmp_path: Temporary directory of the test, holding the copied migrations.
        :type tmp_path: Path
        """
        await _migrate(fx_empty_database, fx_empty_database.migrations.upgrade, 'head')
        project_id = await _commit_book(fx_empty_database)
        migrations = _migrations_with_revision(fx_empty_database, tmp_path / 'migrations', REBUILD_PROJECTS)
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        async with fx_empty_database.sessions() as session:
            for table in BOOK_TABLES:
                expect(await session.scalar(select(func.count()).select_from(table)) == 1, table.__tablename__)
            cover_page_id = await session.scalar(select(ProjectRow.cover_page_id).where(ProjectRow.id == project_id))
        expect(cover_page_id is not None)
        assert_expectations()

    async def test_rows_left_without_their_project_roll_the_migration_back(
        self, fx_empty_database: SqlDatabase, tmp_path: Path
    ) -> None:
        """Verify a revision orphaning the rows of a book fails, and leaves the schema, rows and revision it found.

        The revision rebuilds projects and then deletes them, so both its schema change and its row change have to
        be undone, and the database must stay at the baseline for the application to refuse it.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        :param tmp_path: Temporary directory of the test, holding the copied migrations.
        :type tmp_path: Path
        """
        await _migrate(fx_empty_database, fx_empty_database.migrations.upgrade, 'head')
        await _commit_book(fx_empty_database)
        baseline = await fx_empty_database.schema_revisions()
        migrations = _migrations_with_revision(fx_empty_database, tmp_path / 'migrations', ORPHAN_THE_BOOK)
        with pytest.raises(RuntimeError, match='foreign key to no row'):
            await _migrate(fx_empty_database, migrations.upgrade, 'head')
        async with fx_empty_database.sessions() as session:
            for table in BOOK_TABLES:
                expect(await session.scalar(select(func.count()).select_from(table)) == 1, table.__tablename__)
        async with fx_empty_database.engine.connect() as connection:
            columns = await connection.run_sync(lambda sync: inspect(sync).get_columns(ProjectRow.__tablename__))
        expect(REBUILT_COLUMN not in {column['name'] for column in columns})
        expect((await fx_empty_database.schema_revisions()).database == baseline.database)
        assert_expectations()

    @pytest.mark.parametrize(
        ('column', 'new_type'),
        [
            pytest.param('title', 'Integer', id='string-reflected-by-name'),
            pytest.param('cover_page_id', 'String', id='guid-compared-by-affinity'),
        ],
    )
    async def test_check_notices_a_column_whose_type_differs_from_the_tables(
        self, fx_empty_database: SqlDatabase, tmp_path: Path, column: str, new_type: str
    ) -> None:
        """Verify ``alembic check`` fails on a column of another type, so autogenerate writes type changes too.

        ``title`` has a type SQLite reflects by name, and ``cover_page_id`` a ``GUID`` it reflects by affinity.

        :param fx_empty_database: Database with no table.
        :type fx_empty_database: SqlDatabase
        :param tmp_path: Temporary directory of the test, holding the copied migrations.
        :type tmp_path: Path
        :param column: Column of projects whose type the revision changes.
        :type column: str
        :param new_type: SQLAlchemy type the revision gives the column.
        :type new_type: str
        """
        retype = RETYPE_A_COLUMN.format(column=column, new_type=new_type)
        migrations = _migrations_with_revision(fx_empty_database, tmp_path / 'migrations', retype)
        await _migrate(fx_empty_database, migrations.upgrade, 'head')
        with pytest.raises(AutogenerateDiffsDetected, match='modify_type'):
            await _migrate(fx_empty_database, migrations.check)
