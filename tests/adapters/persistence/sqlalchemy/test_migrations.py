class TestGroupsRevision:
    """Tests for the revision that keeps the groups of the pages as rows."""

    @staticmethod
    async def _grouped_book(database: SqlDatabase) -> PageId:
        """Store a book at the head revision whose page, values and a change of them name one group.

        :param database: Database of a book with no table.
        :type database: SqlDatabase
        :returns: The page of the book.
        :rtype: PageId
        """
        await _migrate(database, database.migrations.upgrade, HEAD)
        await _commit_book(database)
        with _session(database) as session:
            page_id = PageId(session.scalars(select(PageRow.id)).one())

        def group(session: Session) -> None:
            """Put the page, its values and a change of them in the group, beside values of the odd pages.

            :param session: Session of the transaction.
            :type session: Session
            """
            repos = SqlAlchemyBookRepositories(session)
            repos.pages.update(evolve(repos.pages.get(page_id), group_label=GROUP))
            repos.step_values.save_many(
                [make_step_values(scope=ValueScope.GROUP, group_label=GROUP), make_step_values(scope=ValueScope.ODD)]
            )
            repos.page_history.add(
                evolve(make_page_history_entry(page_id=page_id), scope=ValueScope.GROUP, group_label=GROUP)
            )

        await database.write(group, kind=BlockKind.BOOK, book=BOOK_ID, wait_seconds=DEFAULT_CHANGE_WAIT_SECONDS)
        return page_id

    async def test_a_group_keeps_its_page_values_and_changes_both_ways(self, fx_empty_book: SqlDatabase) -> None:
        """Verify the group is a label in every row after the downgrade, and one row they name after the upgrade.

        :param fx_empty_book: Database of a book with no table.
        :type fx_empty_book: SqlDatabase
        """
